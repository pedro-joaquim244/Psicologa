-- PostgreSQL/Supabase schema equivalent to the current MySQL application.
-- This migration creates structure only. It never copies production data.

create schema if not exists extensions;
create extension if not exists citext with schema extensions;
create extension if not exists btree_gist with schema extensions;
set local search_path to public, extensions, pg_catalog;
set local timezone to 'America/Sao_Paulo';

create type public.tipo_usuario_admin as enum ('psicologa', 'admin');
create type public.modalidade_agendamento as enum ('online', 'presencial');
create type public.status_agendamento as enum ('agendado', 'confirmado', 'cancelado', 'concluido');

create or replace function public.set_atualizado_em()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
begin
  new.atualizado_em = current_timestamp;
  return new;
end;
$$;

create table public.profissionais (
  id bigint generated by default as identity primary key,
  nome varchar(150) not null,
  email extensions.citext,
  telefone varchar(30),
  google_calendar_id varchar(255),
  ativo smallint not null default 1 check (ativo in (0, 1)),
  criado_em timestamp without time zone not null default current_timestamp,
  atualizado_em timestamp without time zone not null default current_timestamp,
  constraint ck_profissional_email check (email is null or length(trim(email::text)) between 3 and 255)
);

create unique index uq_profissionais_email on public.profissionais (email) where email is not null;

create table public.usuarios_admin (
  id bigint generated by default as identity primary key,
  nome varchar(150) not null,
  email extensions.citext not null unique,
  senha varchar(255) not null,
  tipo public.tipo_usuario_admin not null default 'psicologa',
  ativo smallint not null default 1 check (ativo in (0, 1)),
  criado_em timestamp without time zone not null default current_timestamp,
  atualizado_em timestamp without time zone not null default current_timestamp,
  email_verificado_em timestamp without time zone,
  profissional_id bigint references public.profissionais(id) on delete set null
);

create index idx_usuario_admin_profissional on public.usuarios_admin (profissional_id);

create table public.pacientes (
  id bigint generated by default as identity primary key,
  nome varchar(150) not null,
  email extensions.citext not null unique,
  telefone varchar(30) not null,
  senha varchar(255) not null,
  ativo smallint not null default 1 check (ativo in (0, 1)),
  criado_em timestamp without time zone not null default current_timestamp,
  email_verificado_em timestamp without time zone
);

create table public.disponibilidades (
  id bigint generated by default as identity primary key,
  profissional_id bigint not null references public.profissionais(id) on delete cascade,
  dia_semana smallint not null check (dia_semana between 0 and 6),
  hora_inicio time without time zone not null,
  hora_fim time without time zone not null,
  duracao_minutos smallint not null default 50 check (duracao_minutos between 1 and 1439),
  intervalo_minutos smallint not null default 10 check (intervalo_minutos between 0 and 1440),
  ativo smallint not null default 1 check (ativo in (0, 1)),
  criado_em timestamp without time zone not null default current_timestamp,
  data_especifica date,
  constraint ck_disponibilidade_intervalo check (hora_inicio < hora_fim),
  constraint ck_disponibilidade_dia_data check (
    data_especifica is null
    or dia_semana = extract(dow from data_especifica)::smallint
  )
);

create index idx_disponibilidade_dia on public.disponibilidades (dia_semana);
create index idx_disponibilidade_data on public.disponibilidades (profissional_id, data_especifica, dia_semana, ativo);
create unique index uq_disponibilidade_exata_ativa
  on public.disponibilidades (
    profissional_id,
    coalesce(data_especifica, date '0001-01-01'),
    dia_semana,
    hora_inicio,
    hora_fim,
    duracao_minutos,
    intervalo_minutos
  ) where ativo = 1;

create table public.bloqueios_agenda (
  id bigint generated by default as identity primary key,
  profissional_id bigint not null references public.profissionais(id) on delete cascade,
  inicio timestamp without time zone,
  fim timestamp without time zone,
  motivo varchar(150),
  criado_em timestamp without time zone not null default current_timestamp,
  dia_semana smallint check (dia_semana between 0 and 6),
  hora_inicio time without time zone,
  hora_fim time without time zone,
  constraint ck_bloqueio_formato check (
    (
      inicio is not null and fim is not null and inicio < fim
      and dia_semana is null and hora_inicio is null and hora_fim is null
    )
    or
    (
      inicio is null and fim is null and dia_semana is not null
      and hora_inicio is not null and hora_fim is not null and hora_inicio < hora_fim
    )
  )
);

create index idx_bloqueios_inicio on public.bloqueios_agenda (inicio);
create index idx_bloqueio_recorrente on public.bloqueios_agenda (profissional_id, dia_semana, hora_inicio, hora_fim);

create table public.agendamentos (
  id bigint generated by default as identity primary key,
  paciente_id bigint references public.pacientes(id) on delete set null,
  profissional_id bigint not null references public.profissionais(id) on delete restrict,
  nome_cliente varchar(150) not null,
  email_cliente extensions.citext,
  telefone_cliente varchar(30) not null,
  modalidade public.modalidade_agendamento not null,
  inicio timestamp without time zone not null,
  fim timestamp without time zone not null,
  status public.status_agendamento not null default 'agendado',
  google_event_id varchar(255),
  origem varchar(100) default 'site',
  slot_ativo smallint generated always as (
    case when status in ('agendado', 'confirmado') then 1 else null end
  ) stored,
  criado_em timestamp without time zone not null default current_timestamp,
  atualizado_em timestamp without time zone not null default current_timestamp,
  token_cancelamento varchar(255) unique,
  constraint ck_agendamento_intervalo check (inicio < fim)
);

-- The application also locks the professional row inside booking transactions.
-- This exclusion constraint is the final database-level guard against every
-- overlapping active interval, including requests handled by different hosts.
alter table public.agendamentos
  add constraint ex_agendamento_sem_sobreposicao
  exclude using gist (
    profissional_id with =,
    tsrange(inicio, fim, '[)') with &&
  ) where (status in ('agendado', 'confirmado'));

create unique index uq_horario_agendamento
  on public.agendamentos (profissional_id, inicio)
  where slot_ativo = 1;
create index idx_agendamentos_inicio on public.agendamentos (inicio);
create index idx_agendamentos_status on public.agendamentos (status);
create index idx_agendamento_paciente on public.agendamentos (paciente_id);

create table public.notificacoes_agendamento (
  id bigint generated by default as identity primary key,
  agendamento_id bigint not null references public.agendamentos(id) on delete cascade,
  tipo varchar(32) not null check (tipo in ('solicitacao', 'confirmacao', 'conclusao', 'cancelamento', 'reagendamento', 'recusa')),
  destinatario extensions.citext,
  status varchar(24) not null default 'pendente' check (status in ('pendente', 'enviando', 'enviado', 'falhou', 'invalido')),
  event_key varchar(180) not null unique,
  dados jsonb not null,
  tentativas smallint not null default 0 check (tentativas between 0 and 255),
  ultima_tentativa_em timestamp without time zone,
  enviado_em timestamp without time zone,
  proxima_tentativa_em timestamp without time zone,
  erro varchar(255),
  criado_em timestamp without time zone not null default current_timestamp,
  atualizado_em timestamp without time zone not null default current_timestamp
);

create index idx_notificacao_retentativa on public.notificacoes_agendamento (status, proxima_tentativa_em);
create index idx_notificacao_agendamento on public.notificacoes_agendamento (agendamento_id);

create table public.verificacoes_email (
  perfil varchar(20) not null check (perfil in ('paciente', 'profissional')),
  usuario_id bigint not null check (usuario_id > 0),
  desafio char(64) collate "C" not null unique,
  email extensions.citext not null,
  codigo_hash char(64) collate "C" not null,
  expira_em bigint not null check (expira_em > 0),
  reenviar_em bigint not null check (reenviar_em > 0),
  janela_ate bigint not null check (janela_ate > 0),
  envios integer not null default 0 check (envios >= 0),
  tentativas integer not null default 0 check (tentativas >= 0),
  consumido smallint not null default 0 check (consumido in (0, 1)),
  primary key (perfil, usuario_id)
);

create trigger trg_profissionais_atualizado_em
before update on public.profissionais
for each row execute function public.set_atualizado_em();

create trigger trg_usuarios_admin_atualizado_em
before update on public.usuarios_admin
for each row execute function public.set_atualizado_em();

create trigger trg_agendamentos_atualizado_em
before update on public.agendamentos
for each row execute function public.set_atualizado_em();

create trigger trg_notificacoes_atualizado_em
before update on public.notificacoes_agendamento
for each row execute function public.set_atualizado_em();

